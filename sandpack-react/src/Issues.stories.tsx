export const Issue482 = (): JSX.Element | null => {
  const [hidden, setHidden] = useState(false);

  const toggleHidden = (): void => {
    setHidden((prevHidden) => !prevHidden);
  };

  const fs = useSandpackFS({
    template: "vanilla",
    customSetup: {
      entry: "/index.js",
    },
    files: {
      "/index.js": {
        code: "// index.js",
        active: true,
      },
      "/index2.js": {
        code: "// index2.js",
      },
      "/src/index.js": {
        code: "// this file is generated by vanilla template, but it is not needed",
        hidden: true,
      },
      "/hidden.js": {
        code: "// hidden.js",
        hidden: true,
      },
    },
  });
  if (!fs) return null;

  return (
    <>
      <button onClick={toggleHidden}>toggle hidden</button>
      <SandpackProvider
        fs={fs}
        options={{
          visibleFiles: ["/index.js", "/hidden.js"],
          activeFile: "/index.js",
        }}
      >
        <SandpackLayout>
          <SandpackFileExplorer autoHiddenFiles={hidden} />
          <SandpackCodeEditor />
        </SandpackLayout>
      </SandpackProvider>
    </>
  );
};

